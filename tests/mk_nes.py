# 테스트용 NES 롬: 배경색을 칠하고 멈춘다 (저작권 없는 직접 만든 롬)
code = bytes([
 0x78,0xD8,0xA2,0xFF,0x9A,            # SEI CLD LDX #$FF TXS
 0x2C,0x02,0x20,0x10,0xFB,            # wait vblank
 0x2C,0x02,0x20,0x10,0xFB,
 0xA9,0x3F,0x8D,0x06,0x20,0xA9,0x00,0x8D,0x06,0x20,  # PPUADDR=$3F00
 0xA9,0x16,0x8D,0x07,0x20,            # color
 0xA9,0x00,0x8D,0x05,0x20,0x8D,0x05,0x20,
 0xA9,0x0A,0x8D,0x01,0x20,            # PPUMASK show bg
 0x4C,0x2F,0x80])                     # JMP self (0x802F)
prg = bytearray(16384); prg[:len(code)] = code
prg[0x3FFA:0x3FFC]=b'\x00\x80'; prg[0x3FFC:0x3FFE]=b'\x00\x80'; prg[0x3FFE:0x4000]=b'\x00\x80'
hdr = b'NES\x1a' + bytes([1,1,0,0]) + bytes(8)
open('tests/test.nes','wb').write(hdr+bytes(prg)+bytes(8192))
